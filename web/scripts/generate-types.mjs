import { compileFromFile } from "json-schema-to-typescript";
import { mkdir, writeFile } from "node:fs/promises";
const root = "../packages/gallery_schema/src/gallery_schema/schemas/v1/";
await mkdir("src/generated", { recursive: true });
for (const [file, name] of [
  ["match_event", "MatchEvent"],
  ["overlay_cue", "OverlayCue"],
  ["agent_trace_event", "AgentTraceEvent"],
]) {
  const result = await compileFromFile(`${root}${file}.schema.json`, {
    bannerComment: "/* Generated by npm run types:generate. Do not edit. */",
    additionalProperties: false,
  });
  // The union schema has no title; give its root a stable public name.
  const text =
    file === "match_event"
      ? result.replace(/export type [\w]+ =/, `export type ${name} =`)
      : result;
  await writeFile(`src/generated/${name}.ts`, text);
}
